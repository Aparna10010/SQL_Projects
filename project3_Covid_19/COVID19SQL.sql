--WHAT ARE THE TOTAL ACTIVE CASES PER REGION :

SELECT 
     REGION,
	 SUM(CONFIRMED - RECOVERED - DEATHS) AS
	 ACTIVE_CASES
FROM
     COVID_19_DATA
GROUP BY
     REGION
ORDER BY
     ACTIVE_CASES DESC;


